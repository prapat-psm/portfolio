// Turns the 1:1 pixel-art portrait into voxel data for the 3D hero portrait.
// Run: node scripts/gen-portrait-voxels.mjs
import { writeFile } from "node:fs/promises";
import sharp from "sharp";

const SRC = "assets/portrait/portrait.png";
const BLINK = "assets/portrait/portrait-blink.png";
const OUT = "components/Theatre/portrait-voxels.data.ts";
/** Pillow-hat colors: these cubes get their own "puff" animation. */
const HAT_COLORS = ["#a9c3ea", "#6e93cc", "#48679e", "#e8eefb", "#a7a9b8", "#7c7e8f", "#55566a"];
/** Rows below this are shoulders, so pillow-colored cells there (earrings, rim) don't count as hat. */
const HAT_MAX_ROW_SHARE = 0.62;

const read = async (file) => {
  const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const hex = (i) =>
    data[i + 3] < 128
      ? "."
      : "#" + [0, 1, 2].map((c) => data[i + c].toString(16).padStart(2, "0")).join("");
  return { info, colors: Array.from({ length: info.width * info.height }, (_, p) => hex(p * 4)) };
};

const base = await read(SRC);
const blink = await read(BLINK);
const { width: cols, height: rows } = base.info;
if (blink.info.width !== cols || blink.info.height !== rows) throw new Error("Blink frame size differs");

const palette = [];
const indexOf = (color) => {
  if (!palette.includes(color)) palette.push(color);
  return palette.indexOf(color);
};

let cells = "";
let hatCells = "";
base.colors.forEach((color, i) => {
  const isHat = HAT_COLORS.includes(color) && Math.floor(i / cols) < rows * HAT_MAX_ROW_SHARE;
  cells += color === "." ? "." : indexOf(color).toString(36);
  hatCells += isHat ? "1" : "0";
});
const blinkDiff = [];
blink.colors.forEach((color, i) => {
  if (color !== base.colors[i] && color !== ".") blinkDiff.push([i, indexOf(color)]);
});
if (palette.length > 36) throw new Error(`Too many colors (${palette.length}) for base-36 cells`);

const chunk = (s) => s.match(new RegExp(`.{${cols}}`, "g")).map((r) => `    "${r}"`).join(" +\n");
const body = `// Generated by scripts/gen-portrait-voxels.mjs from ${SRC}. Do not edit by hand.
import type { VoxelGrid } from "@/libs/voxel-portrait";

export const PORTRAIT_VOXELS: VoxelGrid = {
  cols: ${cols},
  rows: ${rows},
  palette: ${JSON.stringify(palette)},
  cells:
${chunk(cells)},
  hat:
${chunk(hatCells)},
  blink: ${JSON.stringify(blinkDiff)},
};
`;
await writeFile(OUT, body);
console.log(`${cols}x${rows}, ${palette.length} colors, ${cells.replace(/\./g, "").length} voxels, ${blinkDiff.length} blink cells → ${OUT}`);
