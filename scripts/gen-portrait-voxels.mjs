// Turns the hero pixel-art GIF into a compact voxel grid for the 3D portrait.
// Run: node scripts/gen-portrait-voxels.mjs
import { writeFile } from "node:fs/promises";
import sharp from "sharp";

const SRC = "public/portrait.gif";
const OUT = "components/Theatre/portrait-voxels.data.ts";
const COLS = 64;

const { data, info } = await sharp(SRC, { pages: 1 })
  .ensureAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });

const rows = Math.round((COLS * info.height) / info.width);
const cellW = info.width / COLS;
const cellH = info.height / rows;
const hex = (r, g, b) => "#" + [r, g, b].map((v) => v.toString(16).padStart(2, "0")).join("");

const palette = [];
let cells = "";

for (let row = 0; row < rows; row++) {
  for (let col = 0; col < COLS; col++) {
    // Most common color in the cell wins, so anti-aliased edges don't leak in
    const counts = new Map();
    for (let y = Math.floor(row * cellH); y < Math.floor((row + 1) * cellH); y++) {
      for (let x = Math.floor(col * cellW); x < Math.floor((col + 1) * cellW); x++) {
        const i = (y * info.width + x) * 4;
        const key = data[i + 3] < 128 ? "." : hex(data[i], data[i + 1], data[i + 2]);
        counts.set(key, (counts.get(key) ?? 0) + 1);
      }
    }
    const [color] = [...counts.entries()].sort((a, b) => b[1] - a[1])[0];
    if (color === ".") {
      cells += ".";
      continue;
    }
    if (!palette.includes(color)) palette.push(color);
    cells += palette.indexOf(color).toString(36);
  }
}

const body = `// Generated by scripts/gen-portrait-voxels.mjs from ${SRC}. Do not edit by hand.
import type { VoxelGrid } from "@/libs/voxel-portrait";

export const PORTRAIT_VOXELS: VoxelGrid = {
  cols: ${COLS},
  rows: ${rows},
  palette: ${JSON.stringify(palette)},
  cells:
${cells.match(new RegExp(`.{${COLS}}`, "g")).map((r) => `    "${r}"`).join(" +\n")},
};
`;
await writeFile(OUT, body);
console.log(`${COLS}x${rows}, ${palette.length} colors, ${cells.replace(/\./g, "").length} voxels → ${OUT}`);
